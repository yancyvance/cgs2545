DROP DATABASE IF EXISTS grocery;

CREATE DATABASE grocery;

USE grocery;

CREATE TABLE Customer (
    CustomerID         INT NOT NULL,
    FirstName          VARCHAR(50),
    LastName           VARCHAR(50),
    StreetAddress      VARCHAR(100),
    City               VARCHAR(50),
    Zipcode            VARCHAR(10),
    State              CHAR(2),
    ContactNo          VARCHAR(20),
    Email              VARCHAR(100) NOT NULL,

    CONSTRAINT pk_customer
        PRIMARY KEY (CustomerID),

    CONSTRAINT uq_customer_email
        UNIQUE (Email)
);


CREATE TABLE Category (
    CategoryID         INT NOT NULL,
    CategoryName       VARCHAR(50) NOT NULL,

    CONSTRAINT pk_category
        PRIMARY KEY (CategoryID)
);


CREATE TABLE Employee (
    EmployeeID         INT NOT NULL,
    FirstName          VARCHAR(50) NOT NULL,
    LastName           VARCHAR(50) NOT NULL,
    ManagerID          INT,
    DateHired          DATE NOT NULL,

    CONSTRAINT pk_employee
        PRIMARY KEY (EmployeeID),

    CONSTRAINT fk_employee_manager
        FOREIGN KEY (ManagerID)
        REFERENCES Employee (EmployeeID)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);


CREATE TABLE Product (
    ProductID          INT NOT NULL,
    ProductName        VARCHAR(100) NOT NULL,
    UnitPrice          DECIMAL(10,2) NOT NULL,
    CategoryID         INT NOT NULL,

    CONSTRAINT pk_product
        PRIMARY KEY (ProductID),

    CONSTRAINT fk_product_category
        FOREIGN KEY (CategoryID)
        REFERENCES Category (CategoryID)
);


CREATE TABLE OnlineOrder (
    OrderID            INT NOT NULL,
    OrderDate          DATETIME NOT NULL,
    PaymentMethod      VARCHAR(20),
    ShipDate           DATETIME,
    OrderStatus        VARCHAR(20),
    CustomerID         INT NOT NULL,
    EmpID              INT,

    CONSTRAINT pk_onlineorder
        PRIMARY KEY (OrderID),

    CONSTRAINT fk_onlineorder_customer
        FOREIGN KEY (CustomerID)
        REFERENCES Customer (CustomerID),

    CONSTRAINT fk_onlineorder_employee
        FOREIGN KEY (EmpID)
        REFERENCES Employee (EmployeeID)
);


CREATE TABLE OrderDetail (
    OrderDetailID      INT NOT NULL AUTO_INCREMENT,
    OrderID            INT NOT NULL,
    ProductID          INT NOT NULL,
    Qty                INT NOT NULL,

    CONSTRAINT pk_orderdetail
        PRIMARY KEY (OrderDetailID),

    CONSTRAINT fk_orderdetail_order
        FOREIGN KEY (OrderID)
        REFERENCES OnlineOrder (OrderID),

    CONSTRAINT fk_orderdetail_product
        FOREIGN KEY (ProductID)
        REFERENCES Product (ProductID)
);


